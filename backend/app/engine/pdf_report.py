"""
PDF Report generation for AccessReaper v2 using ReportLab.
Produces professional, self-contained audit reports from frozen AuditRun snapshots.
Includes numbered canvas (Page X of Y), Acme, Inc. branding, and risk summaries.
"""

from io import BytesIO
from typing import Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.pdfgen import canvas
from reportlab.platypus import HRFlowable, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.core.time import KARACHI_TZ


class NumberedCanvas(canvas.Canvas):
    org_name = 'payhive-eng'
    """
    Two-pass canvas to dynamically compute total page count and draw
    consistent header/footer page numbers.
    """

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748b"))

        # Footer
        self.drawString(54, 32, "Generated by AccessReaper v2 · Live Production")
        self.drawRightString(612 - 54, 32, f"Page {self._pageNumber} of {page_count}")
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.5)
        self.line(54, 44, 612 - 54, 44)

        # Header on pages 2+
        if self._pageNumber > 1:
            self.drawString(54, 792 - 36, "AccessReaper v2 — Access Audit Report")
            self.drawRightString(612 - 54, 792 - 36, self.org_name)
            self.line(54, 792 - 42, 612 - 54, 792 - 42)

        self.restoreState()


def generate_audit_pdf(run_dict: dict[str, Any], findings_list: list[dict[str, Any]]) -> bytes:
    """
    Renders an audit run and its frozen findings snapshot into a binary PDF.
    """
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#0f172a"),
        spaceAfter=4,
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#475569"),
        spaceAfter=12,
    )
    heading_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#1e293b"),
        spaceBefore=14,
        spaceAfter=8,
    )
    cell_style = ParagraphStyle(
        "TableCell",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#1e293b"),
    )
    cell_bold = ParagraphStyle(
        "TableCellBold",
        parent=cell_style,
        fontName="Helvetica-Bold",
    )
    badge_high = ParagraphStyle(
        "BadgeHigh",
        parent=cell_style,
        fontName="Helvetica-Bold",
        textColor=colors.HexColor("#dc2626"),
    )
    badge_med = ParagraphStyle(
        "BadgeMed",
        parent=cell_style,
        fontName="Helvetica-Bold",
        textColor=colors.HexColor("#d97706"),
    )
    badge_low = ParagraphStyle(
        "BadgeLow",
        parent=cell_style,
        fontName="Helvetica-Bold",
        textColor=colors.HexColor("#16a34a"),
    )

    story = []

    # Title & Subtitle
    story.append(Paragraph("AccessReaper v2 — Access Audit Report", title_style))
    story.append(
        Paragraph(
            "Independent rule-based IAM governance report · Organization: <b>payhive-eng</b>",
            subtitle_style,
        )
    )
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceAfter=14))

    # Run Metadata Table
    run_id = run_dict.get("id", "AUD-UNKNOWN")
    completed_dt = run_dict.get("completed_at")
    if hasattr(completed_dt, "astimezone"):
        completed_str = completed_dt.astimezone(KARACHI_TZ).strftime("%B %d, %Y at %I:%M %p PKT")
    else:
        completed_str = str(completed_dt or "Completed")

    meta_data = [
        [
            Paragraph("<b>Audit Run ID:</b>", cell_style),
            Paragraph(run_id, cell_style),
            Paragraph("<b>Execution Mode:</b>", cell_style),
            Paragraph(f"<b>{run_dict.get('mode', 'LIVE_PRODUCTION')}</b>", cell_style),
        ],
        [
            Paragraph("<b>Completed At:</b>", cell_style),
            Paragraph(completed_str, cell_style),
            Paragraph("<b>Rule Weights:</b>", cell_style),
            Paragraph(f"Version {run_dict.get('rule_version', 1)}", cell_style),
        ],
        [
            Paragraph("<b>Audited By:</b>", cell_style),
            Paragraph(run_dict.get("actor", "Jordan Davis"), cell_style),
            Paragraph("<b>Trigger:</b>", cell_style),
            Paragraph(run_dict.get("trigger", "manual").capitalize(), cell_style),
        ],
    ]
    meta_table = Table(meta_data, colWidths=[90, 162, 90, 162])
    meta_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#f1f5f9")),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ]
        )
    )
    story.append(meta_table)
    story.append(Spacer(1, 12))

    # Executive Summary Totals Table
    story.append(Paragraph("Executive Summary & Risk Distribution", heading_style))
    summary_data = [
        [
            Paragraph("<b>Identities</b>", cell_bold),
            Paragraph("<b>Assignments</b>", cell_bold),
            Paragraph("<b>High Risk</b>", badge_high),
            Paragraph("<b>Medium Risk</b>", badge_med),
            Paragraph("<b>Healthy</b>", badge_low),
            Paragraph("<b>Resolved</b>", cell_bold),
        ],
        [
            Paragraph(str(run_dict.get("identities", 0)), cell_style),
            Paragraph(str(run_dict.get("assignments", 0)), cell_style),
            Paragraph(str(run_dict.get("high", 0)), badge_high),
            Paragraph(str(run_dict.get("medium", 0)), badge_med),
            Paragraph(str(run_dict.get("healthy", 0)), badge_low),
            Paragraph(str(run_dict.get("resolved", 0)), cell_style),
        ],
    ]
    sum_table = Table(summary_data, colWidths=[84, 84, 84, 84, 84, 84])
    sum_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]
        )
    )
    story.append(sum_table)
    story.append(Spacer(1, 12))

    # Sources Breakdown
    story.append(Paragraph("Scope & Platform Breakdown", heading_style))
    sources_data = [
        [
            Paragraph("<b>Platform Source</b>", cell_bold),
            Paragraph("<b>Audited Assignments</b>", cell_bold),
            Paragraph("<b>Resources In Scope</b>", cell_bold),
        ]
    ]
    for s in run_dict.get("sources", []):
        src_name = s.get("source", "Unknown")
        sources_data.append(
            [
                Paragraph(src_name, cell_style),
                Paragraph(str(s.get("assignments", 0)), cell_style),
                Paragraph(str(s.get("resources", 0)), cell_style),
            ]
        )
    src_table = Table(sources_data, colWidths=[168, 168, 168])
    src_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ]
        )
    )
    story.append(src_table)
    story.append(Spacer(1, 14))

    # Frozen Findings Table
    story.append(Paragraph("Captured Findings Snapshot", heading_style))
    findings_rows = [
        [
            Paragraph("<b>ID</b>", cell_bold),
            Paragraph("<b>Identity & Repo</b>", cell_bold),
            Paragraph("<b>Access</b>", cell_bold),
            Paragraph("<b>Risk</b>", cell_bold),
            Paragraph("<b>Primary Reason</b>", cell_bold),
            Paragraph("<b>Action Target</b>", cell_bold),
            Paragraph("<b>Status</b>", cell_bold),
        ]
    ]

    for f in findings_list:
        fid = f.get("id", "")
        person_name = f.get("person") or f.get("name", "Unknown")
        repo = f.get("repo", "")
        access = f.get("access", "")
        risk = f.get("risk", "Low")
        reason = f.get("reason", "")
        target = f.get("target") or f.get("action", "")
        status = f.get("status") or (
            f.get("finding", {}).get("status") if isinstance(f.get("finding"), dict) else "Open"
        )

        if risk == "High":
            risk_para = Paragraph(risk, badge_high)
        elif risk == "Medium":
            risk_para = Paragraph(risk, badge_med)
        else:
            risk_para = Paragraph(risk, badge_low)

        ident_repo = f"<b>{person_name}</b><br/><font color='#64748b'>{repo}</font>"

        findings_rows.append(
            [
                Paragraph(fid, cell_style),
                Paragraph(ident_repo, cell_style),
                Paragraph(access, cell_style),
                risk_para,
                Paragraph(reason, cell_style),
                Paragraph(str(target), cell_style),
                Paragraph(status, cell_style),
            ]
        )

    find_table = Table(findings_rows, colWidths=[48, 114, 46, 44, 134, 64, 54], repeatRows=1)
    find_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#f1f5f9")),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 4),
                ("RIGHTPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )

    # In ReportLab, table headers on repeat rows need style
    for col_idx in range(7):
        find_table.setStyle(TableStyle([("TEXTCOLOR", (col_idx, 0), (col_idx, 0), colors.white)]))

    story.append(find_table)

    doc.build(story, canvasmaker=NumberedCanvas)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    return pdf_bytes
