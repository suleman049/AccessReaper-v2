// Stage 4: AI Audit Summary (Groq/Gemini explanations with deterministic fallback)
const AuditSummary={
  getProvider(report){
    const model = (report?.aiSummary?.model || '').toLowerCase();
    const status = report?.aiSummary?.status;
    if (status === 'success') {
      if (model.includes('gemini')) return 'Gemini';
      return 'Groq';
    }
    return 'Template';
  },
  isLive(report){
    return report?.aiSummary?.status === 'success';
  },
  headerBadge(report){
    if (!this.isLive(report)) return 'Summary';
    return `${this.getProvider(report)} Analysis`;
  },
  disclosureHeader(report){
    if (!this.isLive(report)) {
      return `Audit summary <small>Summary</small>`;
    }
    return `Audit summary <small>${this.getProvider(report)} Analysis</small>`;
  },
  text(report){
    if(report?.aiSummary?.summaryText)return report.aiSummary.summaryText;
    if(!report)return 'Run an access audit to generate an executive report summary.';
    const sources=(report.sources?report.sources.map(s=>s.source).filter(s=>s!=='Firestore').join(' and '):'')||'GitHub';
    return `The latest audit checked ${report.assignments} access assignments for ${report.identities} identities across ${sources}. It recorded ${report.high} high-risk and ${report.medium} medium-risk findings, ${report.healthy} healthy assignments, and ${report.resolved} reviewed findings.`;
  },
  preview(report){
    const live = this.isLive(report);
    const provider = this.getProvider(report);
    const label = live ? `${provider} Analysis` : 'Summary';
    const disclaimer = live
      ? `Generated by ${provider} — verify before acting`
      : 'Generated from report data';
    const mark = live ? `<span class="gemini-mark" aria-hidden="true" style="display:inline-flex;align-items:center;">${uiIcon('sparkles', 14)}</span>` : '';
    const aria = live
      ? `Latest audit summary generated by ${provider}`
      : 'Latest audit summary generated from report data';

    return `<section class="gemini-preview" aria-label="${aria}"><div class="gemini-preview-heading">${mark}<h3>Audit summary</h3><span class="preview-label">${label}</span></div><p>${safe(this.text(report))}</p>${report?`<div class="summary-priority"><strong>${report.high?'Review the high-risk findings first.':report.medium?'Review the medium-risk findings next.':'No open risk findings were recorded.'}</strong><span>${report.high||report.medium?'Confirm the business need and apply the recorded recommendations where appropriate.':'Continue the regular access review process.'}</span></div>`:''}<small>${disclaimer}</small></section>`;
  },
  card(report,busy=false){
    return `<section class="card latest-audit-card"><div class="latest-audit-heading"><div><span class="audit-state">${busy?'Audit in progress':'Latest completed audit'}</span><h2>${report?Governance.date(report.completedAt):'No audit recorded'}</h2><p>${safe(report?.id||(window.automationStatus?.nextRunAt ? ('The first automatic audit runs ' + new Date(window.automationStatus.nextRunAt).toLocaleTimeString([],{hour:'2-digit',minute:'2-digit'})) : 'The first automatic audit runs at 02:00 PKT'))}${report?' · GitHub':''}</p></div>${busy?'<span class="audit-loading" role="status">Scanning organization assignments…</span>':`<button class="btn btn-outline btn-sm" data-audit-report="${safe(report?.id||'')}">View full report</button>`}</div>${busy?'<p class="summary-running">The next summary will appear after the audit completes.</p>':this.preview(report)}<p class="audit-snapshot-note">${report?'Report snapshot at completion. Current findings may change after review decisions.':'Audit snapshot reflects live payhive-eng posture.'}</p></section>`;
  }
};
